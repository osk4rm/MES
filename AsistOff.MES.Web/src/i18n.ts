const messages = { pl, en };

function resolveInitialLocale(): 'pl' | 'en' {
  try {
    const saved = localStorage.getItem('locale');
    if (saved === 'pl' || saved === 'en') return saved;
  } catch { /* ignore */ }
  return 'pl';
}


const messages = { pl, en };

function resolveInitialLocale(): 'pl' | 'en' {
  try {
    const saved = localStorage.getItem('locale');
    if (saved === 'pl' || saved === 'en') return saved;
  } catch { /* ignore */ }
  return 'pl';
}

const i18n = createI18n({
  legacy: false,
  locale: resolveInitialLocale(),
  fallbackLocale: 'en',
  missingWarn: false,
  fallbackWarn: false,
  messages
});

export default i18n;
